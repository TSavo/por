export function portraitLoopsFor(id) {
  return portraitLoops.filter(({ phases, entryAliases }) => phases.includes(id) || entryAliases?.has(id));
}

// A new binding can supersede an earlier one for the same opening portrait.
// Include all candidates, in selection order, in that portrait's proof.
export function portraitLoopSignature(id) {
  return JSON.stringify(portraitLoopsFor(id).map(({ cue, phaseTimes, entryAliases, phases }) => ({
    cue: cue?.toString(),
    phaseTimes,
    entryAliases: entryAliases && [...entryAliases],
    phases,
  })));
}
