"""Lay out the Enhanced code wheel.

    python tools/build-code-wheel.py            write src/codewheel/wheel.json
    python tools/build-code-wheel.py --check    fail if the file differs or a question does not decode

The game asks 13 questions: an Espruar rune, a Dethek rune and a path, and it expects one word for
each (qa/research/code-wheel.md). Those 13 are all the program holds. This lays out a whole wheel
that gives exactly those answers and fills every other position with letters chosen by a fixed
random seed, so the wheel is complete and the same every time it is built.

The wheel has two discs with 36 positions each.
- The outer disc carries 36 Espruar runes on its rim and six rings of 36 letters.
- The inner disc carries 36 Dethek runes and three paths. A path is six windows, one over each
  letter ring. Turn the inner disc until the Dethek rune sits against the Espruar rune, and read
  the letters in the path's windows from the inside to the outside.
"""
import json, random, sys
from pathlib import Path

POSITIONS, RINGS = 36, 6
OUT = Path(__file__).resolve().parents[1] / "src" / "codewheel" / "wheel.json"
PATHS = ["dashes", "dash-dot-dot", "dots"]
# The game's table: word, the two glyph codes of the Espruar rune, the glyph codes of the Dethek rune.
QUESTIONS = [
    ("BEWARE", "1d1e", "6c70"), ("ZOMBIE", "5b5c", "4d"), ("NOTNOW", "2c2d", "6a"), ("COPPER", "090a", "43"),
    ("DRAGON", "0102", "68"), ("EFREET", "1112", "6d"), ("FRIEND", "1718", "3f"), ("JUNGLE", "191a", "4e"),
    ("KNIGHT", "2223", "6c"), ("SAVIOR", "2e2f", "42"), ("TEMPLE", "3637", "4b"), ("VULCAN", "3435", "6e"),
    ("WYVERN", "2c2d", "47"),
]
# Where each path's six windows sit on the inner disc, innermost ring first. The three paths start
# a third of a turn apart; the second curls one way and the third the other.
WINDOWS = [[0] * RINGS, [(12 + ring) % POSITIONS for ring in range(RINGS)], [(24 - ring) % POSITIONS for ring in range(RINGS)]]


def build():
    rng = random.Random(1988)
    espruar_needed = list(dict.fromkeys(e for _, e, _ in QUESTIONS))
    dethek_needed = list(dict.fromkeys(d for _, _, d in QUESTIONS))
    while True:
        # Put the runes the game uses at random positions, and try again if two questions would
        # need different letters in the same place.
        espruar_at = dict(zip(espruar_needed, rng.sample(range(POSITIONS), len(espruar_needed))))
        dethek_at = dict(zip(dethek_needed, rng.sample(range(POSITIONS), len(dethek_needed))))
        letters = [[None] * POSITIONS for _ in range(RINGS)]
        clash = False
        for number, (word, espruar, dethek) in enumerate(QUESTIONS):
            turn = espruar_at[espruar] - dethek_at[dethek]
            for ring in range(RINGS):
                at = (WINDOWS[number % 3][ring] + turn) % POSITIONS
                if letters[ring][at] not in (None, word[ring]):
                    clash = True
                letters[ring][at] = word[ring]
        if not clash:
            break
    rings = ["".join(letter or rng.choice("ABCDEFGHIJKLMNOPQRSTUVWXYZ") for letter in ring) for ring in letters]

    def rim(placed, prefix):
        spare = iter(f"{prefix}-spare-{n:02d}" for n in range(1, POSITIONS + 1))
        by_position = {position: f"{prefix}-{code}" for code, position in placed.items()}
        return [by_position.get(position) or next(spare) for position in range(POSITIONS)]

    return {
        "schema": 1,
        "note": "Generated by tools/build-code-wheel.py. Do not edit.",
        "positions": POSITIONS,
        "outer": {"runes": rim(espruar_at, "espruar"), "rings": rings},
        "inner": {"runes": rim(dethek_at, "dethek"),
                  "paths": [{"id": name, "windows": WINDOWS[index]} for index, name in enumerate(PATHS)]},
        "questions": [{"number": number, "word": word, "espruar": f"espruar-{espruar}", "dethek": f"dethek-{dethek}",
                       "path": PATHS[number % 3]} for number, (word, espruar, dethek) in enumerate(QUESTIONS)],
    }


def read(wheel, espruar, dethek, path):
    """The word the wheel shows for a rune pair and a path."""
    turn = wheel["outer"]["runes"].index(espruar) - wheel["inner"]["runes"].index(dethek)
    windows = next(entry["windows"] for entry in wheel["inner"]["paths"] if entry["id"] == path)
    return "".join(wheel["outer"]["rings"][ring][(windows[ring] + turn) % wheel["positions"]] for ring in range(RINGS))


wheel = build()
for question in wheel["questions"]:
    shown = read(wheel, question["espruar"], question["dethek"], question["path"])
    if shown != question["word"]:
        raise SystemExit(f"question {question['number']} reads {shown}, expected {question['word']}")
text = json.dumps(wheel, indent=2) + "\n"
if "--check" in sys.argv:
    if not OUT.exists() or OUT.read_text() != text:
        raise SystemExit("src/codewheel/wheel.json does not match tools/build-code-wheel.py")
    print(f"verified the code wheel layout: all {len(wheel['questions'])} questions read their word")
else:
    OUT.write_text(text)
    print(f"wrote {OUT.relative_to(OUT.parents[2])}: {POSITIONS} positions, {RINGS} rings, {len(PATHS)} paths")
