import { createHash } from "node:crypto";
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";

// The register of places where the sources disagree.
//
//   npm run qa:disagreements            rebuild qa/disagreements.json and print the counts
//   npm run qa:disagreements -- --check fail if the file is out of date
//
// Every acceptance scenario in qa/acceptance records, with citations, where the walkthroughs,
// the SSI Clue Book, the Adventurer's Journal and the game's own text disagree. This collects
// those notes into one list, one entry per distinct note, with the scenarios that carry it.
// Each entry has a status: "open" until the game itself has been used to settle it, then
// "settled" with what the game does and how that was established. Entries added by hand in
// qa/disagreements-manual.json (errors found in our own digest, for example) are merged in.
// A status and resolution written into qa/disagreements.json are kept when the list is rebuilt.

interface Entry {
  id: string;
  area: string;
  note: string;
  scenarios: string[];
  status: "open" | "settled";
  resolution?: string;
  origin: "acceptance" | "manual";
}

const root = new URL("../qa/", import.meta.url);
const output = new URL("disagreements.json", root);
const previous = new Map<string, Entry>(existsSync(output)
  ? (JSON.parse(readFileSync(output, "utf8")) as { entries: Entry[] }).entries.map(entry => [entry.id, entry]) : []);
const entries = new Map<string, Entry>();
const keep = (entry: Entry) => {
  const before = previous.get(entry.id);
  if (before?.status === "settled") Object.assign(entry, { status: before.status, resolution: before.resolution });
  entries.set(entry.id, entry);
};
const idFor = (note: string) => `disagreement.${createHash("sha256").update(note.replace(/\s+/g, " ").trim()).digest("hex").slice(0, 10)}`;

const folder = new URL("acceptance/", root);
for (const file of readdirSync(folder).filter(name => name.endsWith(".json")).sort()) {
  const area = JSON.parse(readFileSync(new URL(file, folder), "utf8")) as
    { title: string; scenarios: { id: string; disagreements?: string[] }[] };
  for (const scenario of area.scenarios) {
    for (const note of scenario.disagreements ?? []) {
      const id = idFor(note);
      const found = entries.get(id);
      if (found) found.scenarios.push(scenario.id);
      else keep({ id, area: area.title, note: note.replace(/\s+/g, " ").trim(), scenarios: [scenario.id], status: "open", origin: "acceptance" });
    }
  }
}
const manual = new URL("disagreements-manual.json", root);
if (existsSync(manual)) {
  for (const item of (JSON.parse(readFileSync(manual, "utf8")) as { entries: { area: string; note: string }[] }).entries) {
    keep({ id: idFor(item.note), area: item.area, note: item.note, scenarios: [], status: "open", origin: "manual" });
  }
}
const list = [...entries.values()];
const text = JSON.stringify({
  schema: 1,
  note: "Generated by tools/qa-disagreements.ts from qa/acceptance and qa/disagreements-manual.json. Edit only status and resolution here.",
  entries: list,
}, null, 2) + "\n";
if (process.argv.includes("--check")) {
  if (!existsSync(output) || readFileSync(output, "utf8") !== text) {
    console.error("qa/disagreements.json is out of date. Run `npm run qa:disagreements`.");
    process.exit(1);
  }
} else writeFileSync(output, text);
const byArea = new Map<string, { open: number; settled: number }>();
for (const entry of list) {
  const count = byArea.get(entry.area) ?? { open: 0, settled: 0 };
  count[entry.status]++;
  byArea.set(entry.area, count);
}
console.log(`${"area".padEnd(30)} ${"open".padStart(5)} ${"settled".padStart(8)}`);
for (const [area, count] of byArea) console.log(`${area.padEnd(30)} ${String(count.open).padStart(5)} ${String(count.settled).padStart(8)}`);
const open = list.filter(({ status }) => status === "open").length;
console.log(`\n${list.length} recorded disagreements between sources: ${open} open, ${list.length - open} settled against the game`);
